"""Write supabase/schema.sql: the full HMS schema + base data for pasting into the Supabase SQL Editor.

    python -m scripts.export_schema_sql

The SQL is generated from the SQLAlchemy models (identical to `alembic upgrade head`) and also:
- enables Row Level Security on every table with NO policies, so Supabase's public Data API
  (publishable key) cannot read or write anything; the HMS backend connects as the database owner;
- inserts roles, permissions and role grants from app/core/roles.py, departments and the hospital;
- records the Alembic version, so future migrations apply on top with `alembic upgrade head`.
"""
import re
from pathlib import Path

from sqlalchemy import UniqueConstraint, create_mock_engine
from sqlalchemy.schema import AddConstraint, CreateIndex, CreateTable

import app.models_registry  # noqa: F401  (registers every model on Base.metadata)
from app.core import roles as R
from app.core.database import Base
from scripts.seed import DEPARTMENTS

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "supabase" / "schema.sql"


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def alembic_head() -> str:
    from alembic.config import Config
    from alembic.script import ScriptDirectory
    return ScriptDirectory.from_config(Config(str(Path(__file__).resolve().parents[1] / "alembic.ini"))).get_current_head()


def main() -> None:
    engine = create_mock_engine("postgresql+psycopg://", lambda *a, **k: None)
    dialect = engine.dialect
    tables = Base.metadata.sorted_tables
    out: list[str] = [
        "-- Dua Medical HMS: database schema for Supabase (generated by scripts/export_schema_sql.py).",
        "-- Run once on an EMPTY database in Supabase > SQL Editor. Safe to read; do not edit by hand.",
        "",
        "BEGIN;",
        "",
        "-- ================================================================ tables",
    ]
    for t in tables:
        ddl = str(CreateTable(t).compile(dialect=dialect)).strip()
        # Inside CREATE TABLE, PostgreSQL silently merges a UNIQUE that duplicates the primary key.
        # The migrations add such constraints with ALTER TABLE (kept separate), so do the same here.
        pk_cols = [c.name for c in t.primary_key.columns]
        dup_uniques = [c for c in t.constraints if isinstance(c, UniqueConstraint) and c.name
                       and [col.name for col in c.columns] == pk_cols]
        for c in dup_uniques:
            ddl = re.sub(rf",\s*\n\s*CONSTRAINT {re.escape(c.name)} UNIQUE \([^)]*\)", "", ddl)
        out.append(ddl + ";\n")
        for c in dup_uniques:
            out.append(str(AddConstraint(c).compile(dialect=dialect)).strip() + ";\n")
        for ix in sorted(t.indexes, key=lambda i: i.name or ""):
            out.append(str(CreateIndex(ix).compile(dialect=dialect)).strip() + ";")
        if t.indexes:
            out.append("")

    out += ["-- ================================================================ security",
            "-- Row Level Security ON with no policies = the Supabase Data API (publishable/anon key) has",
            "-- no access to any table. The HMS API connects as the owner and is not affected.",
            *[f"ALTER TABLE public.{t.name} ENABLE ROW LEVEL SECURITY;" for t in tables],
            "", "-- ================================================================ base data"]

    out.append("INSERT INTO permissions (id, key, module, description) VALUES")
    out.append(",\n".join(f"  (gen_random_uuid(), {q(k)}, {q(k.split('.', 1)[0])}, {q(d)})" for k, d in R.PERMISSIONS.items()) + ";")
    out.append("\nINSERT INTO roles (id, name, description) VALUES")
    out.append(",\n".join(f"  (gen_random_uuid(), {q(n)}, {q(R.ROLE_DESCRIPTIONS[n])})" for n in R.ROLES) + ";")
    pairs = [(role, perm) for role in R.ROLES for perm in R.ROLE_PERMISSIONS[role]]
    out.append("\nINSERT INTO role_permissions (role_id, permission_id)\nSELECT r.id, p.id FROM (VALUES")
    out.append(",\n".join(f"  ({q(r)}, {q(p)})" for r, p in pairs))
    out.append(") AS g(role_name, permission_key)\nJOIN roles r ON r.name = g.role_name\nJOIN permissions p ON p.key = g.permission_key;")
    out.append("\nINSERT INTO departments (id, code, name, is_active) VALUES")
    out.append(",\n".join(f"  (gen_random_uuid(), {q(c)}, {q(n)}, true)" for c, n in DEPARTMENTS) + ";")
    out += [
        "\nINSERT INTO hospitals (id, name, code, address, is_active) VALUES (gen_random_uuid(), 'Dua Medical Hospital', 'MAIN', 'Pakistan', true);",
        "INSERT INTO hospital_settings (id, hospital_id, currency, timezone, locale)",
        "  SELECT gen_random_uuid(), id, 'PKR', 'Asia/Karachi', 'en' FROM hospitals WHERE code = 'MAIN';",
        "INSERT INTO inventory_locations (id, code, name) VALUES (gen_random_uuid(), 'MAIN-PHARMACY', 'Medical Store');",
        "",
        "-- ================================================================ migrations bookkeeping",
        "CREATE TABLE alembic_version (version_num VARCHAR(32) NOT NULL, CONSTRAINT alembic_version_pkc PRIMARY KEY (version_num));",
        "ALTER TABLE public.alembic_version ENABLE ROW LEVEL SECURITY;",
        f"INSERT INTO alembic_version (version_num) VALUES ({q(alembic_head())});",
        "",
        "COMMIT;",
        "",
        "-- Next: create the first Admin from the API folder (never insert passwords by hand):",
        "--   python -m scripts.create_initial_admin --username admin --password '<12+ characters>'",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {OUT} ({len(tables)} tables, {len(R.PERMISSIONS)} permissions, {len(R.ROLES)} roles)")


if __name__ == "__main__":
    main()
